"""
NeuroFusion AI
Prepare nested subject-level cross-validation splits for the sMRI branch.

Purpose
-------
For each existing outer CV fold:

    Outer TEST
        -> remains completely untouched

    Outer TRAIN
        -> split into INNER TRAIN + INNER VALIDATION

The outer folds were already generated by:
    src/create_smri_cross_validation_splits.py

This script does NOT:
- train a CNN
- modify the baseline 70/15/15 split
- modify the outer CV assignments
- use outer-test subjects for model selection

Strategy
--------
Outer CV:
    5-fold stratification by diagnosis + acquisition source.

Inner CV:
    4-fold stratification by diagnosis + acquisition source.
    One inner fold is used as validation while the remaining
    three inner folds are used for training.

Thus each outer fold produces:

    INNER TRAIN
    INNER VALIDATION
    OUTER TEST

The inner validation fold is used for model selection / early stopping.
The outer test fold remains untouched until final evaluation.

Outputs
-------
processed_data/smri/cnn_dataset/cross_validation/nested/

    outer_fold_1/
        inner_split_1.csv
        inner_split_2.csv
        inner_split_3.csv
        inner_split_4.csv

    outer_fold_2/
        ...

    outer_fold_5/
        ...

    nested_cv_assignments.csv
    nested_cv_summary.csv
    nested_cv_validation_report.txt
"""

from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.model_selection import StratifiedKFold


# ============================================================
# PATHS
# ============================================================

ROOT = Path("processed_data") / "smri"

CNN_DATASET_DIR = ROOT / "cnn_dataset"

OUTER_ASSIGNMENTS_FILE = (
    CNN_DATASET_DIR
    / "cross_validation"
    / "cv_assignments.csv"
)

OUTPUT_DIR = (
    CNN_DATASET_DIR
    / "cross_validation"
    / "nested"
)

MASTER_ASSIGNMENTS_FILE = (
    OUTPUT_DIR
    / "nested_cv_assignments.csv"
)

SUMMARY_FILE = (
    OUTPUT_DIR
    / "nested_cv_summary.csv"
)

VALIDATION_REPORT = (
    OUTPUT_DIR
    / "nested_cv_validation_report.txt"
)


# ============================================================
# CONFIGURATION
# ============================================================

OUTER_FOLDS = 5
INNER_FOLDS = 4

RANDOM_SEED = 42

EXPECTED_SUBJECTS = 172


# ============================================================
# STRATIFICATION
# ============================================================

def make_stratum(
    label: int,
    acquisition_source: str,
) -> str:
    """
    Create the diagnosis/source stratification variable.
    """

    if label == 0 and acquisition_source == "LEGACY":
        return "CONTROL_LEGACY"

    if label == 0 and acquisition_source == "RMS":
        return "CONTROL_RMS"

    if label == 1 and acquisition_source == "RMS":
        return "SCHIZOPHRENIA_RMS"

    if label == 1 and acquisition_source == "LEGACY":
        return "SCHIZOPHRENIA_LEGACY"

    raise ValueError(
        "Unexpected label/source combination: "
        f"label={label}, "
        f"source={acquisition_source}"
    )


# ============================================================
# INPUT VALIDATION
# ============================================================

def validate_outer_assignments(
    df: pd.DataFrame,
) -> list[str]:
    """
    Validate the existing outer CV assignment file.
    """

    errors = []

    required_columns = {
        "subject_id",
        "label",
        "acquisition_source",
        "cv_stratum",
        "fold",
    }

    missing = required_columns.difference(
        df.columns
    )

    if missing:
        errors.append(
            "Missing required columns: "
            + ", ".join(sorted(missing))
        )
        return errors

    if len(df) != EXPECTED_SUBJECTS:
        errors.append(
            f"Expected {EXPECTED_SUBJECTS} subjects; "
            f"found {len(df)}"
        )

    if df["subject_id"].duplicated().any():
        errors.append(
            "Duplicate subject IDs found."
        )

    expected_folds = set(
        range(1, OUTER_FOLDS + 1)
    )

    actual_folds = set(
        pd.to_numeric(
            df["fold"],
            errors="coerce",
        ).dropna().astype(int)
    )

    if actual_folds != expected_folds:
        errors.append(
            f"Expected outer folds "
            f"{sorted(expected_folds)}; "
            f"found {sorted(actual_folds)}"
        )

    labels = pd.to_numeric(
        df["label"],
        errors="coerce",
    )

    if labels.isna().any():
        errors.append(
            "Missing/non-numeric labels."
        )

    if not labels.isin([0, 1]).all():
        errors.append(
            "Non-binary labels found."
        )

    sources = set(
        df["acquisition_source"]
        .astype(str)
    )

    if not sources.issubset(
        {"RMS", "LEGACY"}
    ):
        errors.append(
            "Invalid acquisition source detected."
        )

    # Verify the stored stratum agrees with label/source.
    expected_strata = [
        make_stratum(
            int(label),
            str(source),
        )
        for label, source in zip(
            labels,
            df["acquisition_source"],
        )
    ]

    if (
        df["cv_stratum"]
        .astype(str)
        .tolist()
        != expected_strata
    ):
        errors.append(
            "cv_stratum does not match "
            "label/acquisition_source."
        )

    return errors


# ============================================================
# INNER SPLIT VALIDATION
# ============================================================

def validate_nested_assignments(
    nested_df: pd.DataFrame,
) -> list[str]:
    """
    Validate complete nested CV assignments.
    """

    errors = []

    required_columns = {
        "subject_id",
        "label",
        "acquisition_source",
        "cv_stratum",
        "outer_fold",
        "inner_fold",
        "role",
    }

    missing = required_columns.difference(
        nested_df.columns
    )

    if missing:
        errors.append(
            "Nested assignment file missing columns: "
            + ", ".join(sorted(missing))
        )
        return errors

    # --------------------------------------------------------
    # Every subject should occur once per outer fold.
    #
    # There are INNER_FOLDS records for every subject:
    # each record corresponds to one possible inner validation
    # split inside that subject's outer training set.
    # --------------------------------------------------------

    expected_rows = (
        EXPECTED_SUBJECTS
        * OUTER_FOLDS
        * INNER_FOLDS
    )

    if len(nested_df) != expected_rows:
        errors.append(
            f"Expected {expected_rows} nested assignment rows; "
            f"found {len(nested_df)}"
        )

    # --------------------------------------------------------
    # Validate outer-fold membership
    # --------------------------------------------------------

    for outer_fold in range(
        1,
        OUTER_FOLDS + 1,
    ):

        outer_df = nested_df[
            nested_df["outer_fold"]
            == outer_fold
        ]

        if outer_df.empty:
            errors.append(
                f"Outer fold {outer_fold} is empty."
            )
            continue

        # Subjects in this outer test fold.
        outer_test_subjects = set(
            outer_df.loc[
                outer_df["role"]
                == "OUTER_TEST",
                "subject_id",
            ]
            .astype(str)
        )

        # The same outer test subject should appear
        # once for every inner split.
        counts = (
            outer_df.loc[
                outer_df["role"]
                == "OUTER_TEST"
            ]
            .groupby("subject_id")
            .size()
        )

        if not (
            counts == INNER_FOLDS
        ).all():

            errors.append(
                f"Outer fold {outer_fold}: "
                "outer-test subjects do not appear "
                f"exactly {INNER_FOLDS} times."
            )

        # Outer test subjects must never appear in
        # inner train or inner validation.
        inner_subjects = set(
            outer_df.loc[
                outer_df["role"].isin(
                    {
                        "INNER_TRAIN",
                        "INNER_VALIDATION",
                    }
                ),
                "subject_id",
            ]
            .astype(str)
        )

        overlap = (
            outer_test_subjects
            .intersection(inner_subjects)
        )

        if overlap:
            errors.append(
                f"Outer fold {outer_fold}: "
                "outer test leakage into inner data: "
                + ", ".join(
                    sorted(overlap)
                )
            )

        # ----------------------------------------------------
        # Validate each inner split
        # ----------------------------------------------------

        for inner_fold in range(
            1,
            INNER_FOLDS + 1,
        ):

            split_df = outer_df[
                outer_df["inner_fold"]
                == inner_fold
            ]

            train_ids = set(
                split_df.loc[
                    split_df["role"]
                    == "INNER_TRAIN",
                    "subject_id",
                ]
                .astype(str)
            )

            validation_ids = set(
                split_df.loc[
                    split_df["role"]
                    == "INNER_VALIDATION",
                    "subject_id",
                ]
                .astype(str)
            )

            test_ids = set(
                split_df.loc[
                    split_df["role"]
                    == "OUTER_TEST",
                    "subject_id",
                ]
                .astype(str)
            )

            if train_ids & validation_ids:
                errors.append(
                    f"Outer {outer_fold}, "
                    f"inner {inner_fold}: "
                    "train/validation overlap."
                )

            if train_ids & test_ids:
                errors.append(
                    f"Outer {outer_fold}, "
                    f"inner {inner_fold}: "
                    "train/outer-test overlap."
                )

            if validation_ids & test_ids:
                errors.append(
                    f"Outer {outer_fold}, "
                    f"inner {inner_fold}: "
                    "validation/outer-test overlap."
                )

            # Every subject in the outer training set
            # must belong to exactly one of inner train
            # or inner validation.
            combined = (
                train_ids
                | validation_ids
            )

            expected_outer_train = set(
                outer_df.loc[
                    outer_df["role"]
                    != "OUTER_TEST",
                    "subject_id",
                ]
                .astype(str)
            )

            if combined != expected_outer_train:
                errors.append(
                    f"Outer {outer_fold}, "
                    f"inner {inner_fold}: "
                    "inner train/validation does not "
                    "cover exactly the outer training set."
                )

            # ------------------------------------------------
            # Both classes must exist in inner train and
            # inner validation.
            # ------------------------------------------------

            train_labels = split_df.loc[
                split_df["role"]
                == "INNER_TRAIN",
                "label",
            ].astype(int)

            validation_labels = split_df.loc[
                split_df["role"]
                == "INNER_VALIDATION",
                "label",
            ].astype(int)

            if set(train_labels) != {0, 1}:
                errors.append(
                    f"Outer {outer_fold}, "
                    f"inner {inner_fold}: "
                    "inner training set does not "
                    "contain both classes."
                )

            if set(validation_labels) != {0, 1}:
                errors.append(
                    f"Outer {outer_fold}, "
                    f"inner {inner_fold}: "
                    "inner validation set does not "
                    "contain both classes."
                )

    return errors


# ============================================================
# MAIN
# ============================================================

def main() -> None:

    print("=" * 72)
    print(
        "NeuroFusion AI - PREPARE NESTED sMRI CV SPLITS"
    )
    print("=" * 72)
    print()

    # --------------------------------------------------------
    # Check input
    # --------------------------------------------------------

    if not OUTER_ASSIGNMENTS_FILE.exists():
        raise FileNotFoundError(
            "Outer CV assignments not found:\n"
            f"{OUTER_ASSIGNMENTS_FILE}"
        )

    outer_df = pd.read_csv(
        OUTER_ASSIGNMENTS_FILE
    )

    print(
        f"Outer assignment file : "
        f"{OUTER_ASSIGNMENTS_FILE}"
    )

    print(
        f"Rows                  : "
        f"{len(outer_df)}"
    )

    # --------------------------------------------------------
    # Validate outer assignments
    # --------------------------------------------------------

    outer_errors = (
        validate_outer_assignments(
            outer_df
        )
    )

    if outer_errors:

        print()
        print(
            "OUTER CV VALIDATION: FAIL"
        )

        for error in outer_errors:
            print(
                f"  - {error}"
            )

        raise SystemExit(1)

    print(
        "Outer CV validation    : PASS"
    )
    print()

    # --------------------------------------------------------
    # Normalize types
    # --------------------------------------------------------

    outer_df = outer_df.copy()

    outer_df["subject_id"] = (
        outer_df["subject_id"]
        .astype(str)
        .str.strip()
    )

    outer_df["label"] = (
        pd.to_numeric(
            outer_df["label"],
            errors="raise",
        )
        .astype(int)
    )

    outer_df["acquisition_source"] = (
        outer_df["acquisition_source"]
        .astype(str)
        .str.strip()
    )

    outer_df["cv_stratum"] = [
        make_stratum(
            int(label),
            str(source),
        )
        for label, source in zip(
            outer_df["label"],
            outer_df["acquisition_source"],
        )
    ]

    outer_df["fold"] = (
        pd.to_numeric(
            outer_df["fold"],
            errors="raise",
        )
        .astype(int)
    )

    # --------------------------------------------------------
    # Create output directory
    # --------------------------------------------------------

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # Build nested assignments
    # --------------------------------------------------------

    nested_rows = []

    summary_rows = []

    for outer_fold in range(
        1,
        OUTER_FOLDS + 1,
    ):

        outer_test = outer_df[
            outer_df["fold"]
            == outer_fold
        ].copy()

        outer_train = outer_df[
            outer_df["fold"]
            != outer_fold
        ].copy()

        print(
            f"Outer fold {outer_fold}: "
            f"train={len(outer_train)}, "
            f"test={len(outer_test)}"
        )

        # ----------------------------------------------------
        # Inner stratification
        # ----------------------------------------------------

        inner_strata = outer_train[
            "cv_stratum"
        ].astype(str)

        inner_splitter = StratifiedKFold(
            n_splits=INNER_FOLDS,
            shuffle=True,
            random_state=(
                RANDOM_SEED
                + outer_fold
            ),
        )

        inner_indices = np.arange(
            len(outer_train)
        )

        for inner_fold, (
            inner_train_indices,
            inner_validation_indices,
        ) in enumerate(
            inner_splitter.split(
                inner_indices,
                inner_strata,
            ),
            start=1,
        ):

            inner_train = outer_train.iloc[
                inner_train_indices
            ].copy()

            inner_validation = outer_train.iloc[
                inner_validation_indices
            ].copy()

            # ------------------------------------------------
            # Store inner training subjects
            # ------------------------------------------------

            for _, row in inner_train.iterrows():

                nested_rows.append(
                    {
                        "subject_id":
                            row["subject_id"],
                        "label":
                            int(row["label"]),
                        "acquisition_source":
                            row["acquisition_source"],
                        "cv_stratum":
                            row["cv_stratum"],
                        "outer_fold":
                            outer_fold,
                        "inner_fold":
                            inner_fold,
                        "role":
                            "INNER_TRAIN",
                    }
                )

            # ------------------------------------------------
            # Store inner validation subjects
            # ------------------------------------------------

            for _, row in inner_validation.iterrows():

                nested_rows.append(
                    {
                        "subject_id":
                            row["subject_id"],
                        "label":
                            int(row["label"]),
                        "acquisition_source":
                            row["acquisition_source"],
                        "cv_stratum":
                            row["cv_stratum"],
                        "outer_fold":
                            outer_fold,
                        "inner_fold":
                            inner_fold,
                        "role":
                            "INNER_VALIDATION",
                    }
                )

            # ------------------------------------------------
            # Store outer test subjects.
            #
            # They are repeated for every inner split
            # only so each complete training configuration
            # can be represented explicitly.
            # ------------------------------------------------

            for _, row in outer_test.iterrows():

                nested_rows.append(
                    {
                        "subject_id":
                            row["subject_id"],
                        "label":
                            int(row["label"]),
                        "acquisition_source":
                            row["acquisition_source"],
                        "cv_stratum":
                            row["cv_stratum"],
                        "outer_fold":
                            outer_fold,
                        "inner_fold":
                            inner_fold,
                        "role":
                            "OUTER_TEST",
                    }
                )

            summary_rows.append(
                {
                    "outer_fold":
                        outer_fold,
                    "inner_fold":
                        inner_fold,
                    "inner_train_subjects":
                        len(inner_train),
                    "inner_validation_subjects":
                        len(inner_validation),
                    "outer_test_subjects":
                        len(outer_test),
                    "inner_train_controls":
                        int(
                            (
                                inner_train["label"]
                                == 0
                            ).sum()
                        ),
                    "inner_train_schizophrenia":
                        int(
                            (
                                inner_train["label"]
                                == 1
                            ).sum()
                        ),
                    "inner_validation_controls":
                        int(
                            (
                                inner_validation["label"]
                                == 0
                            ).sum()
                        ),
                    "inner_validation_schizophrenia":
                        int(
                            (
                                inner_validation["label"]
                                == 1
                            ).sum()
                        ),
                    "outer_test_controls":
                        int(
                            (
                                outer_test["label"]
                                == 0
                            ).sum()
                        ),
                    "outer_test_schizophrenia":
                        int(
                            (
                                outer_test["label"]
                                == 1
                            ).sum()
                        ),
                }
            )

    # --------------------------------------------------------
    # Create master DataFrame
    # --------------------------------------------------------

    nested_df = pd.DataFrame(
        nested_rows
    )

    summary_df = pd.DataFrame(
        summary_rows
    )

    # --------------------------------------------------------
    # Validate nested assignments
    # --------------------------------------------------------

    nested_errors = (
        validate_nested_assignments(
            nested_df
        )
    )

    # --------------------------------------------------------
    # Save master assignments
    # --------------------------------------------------------

    nested_df = nested_df.sort_values(
        [
            "outer_fold",
            "inner_fold",
            "role",
            "subject_id",
        ]
    ).reset_index(drop=True)

    nested_df.to_csv(
        MASTER_ASSIGNMENTS_FILE,
        index=False,
        encoding="utf-8",
    )

    summary_df = summary_df.sort_values(
        [
            "outer_fold",
            "inner_fold",
        ]
    ).reset_index(drop=True)

    summary_df.to_csv(
        SUMMARY_FILE,
        index=False,
        encoding="utf-8",
    )

    # --------------------------------------------------------
    # Save individual inner split files
    # --------------------------------------------------------

    for outer_fold in range(
        1,
        OUTER_FOLDS + 1,
    ):

        outer_dir = (
            OUTPUT_DIR
            / f"outer_fold_{outer_fold}"
        )

        outer_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        for inner_fold in range(
            1,
            INNER_FOLDS + 1,
        ):

            split_df = nested_df[
                (
                    nested_df["outer_fold"]
                    == outer_fold
                )
                &
                (
                    nested_df["inner_fold"]
                    == inner_fold
                )
            ].copy()

            split_file = (
                outer_dir
                / f"inner_split_{inner_fold}.csv"
            )

            split_df.to_csv(
                split_file,
                index=False,
                encoding="utf-8",
            )

    # --------------------------------------------------------
    # Validation report
    # --------------------------------------------------------

    report_lines = [
        "NeuroFusion AI - Nested sMRI CV Split Validation",
        "=" * 72,
        "",
        f"Subjects                 : {EXPECTED_SUBJECTS}",
        f"Outer folds              : {OUTER_FOLDS}",
        f"Inner folds per outer    : {INNER_FOLDS}",
        f"Random seed              : {RANDOM_SEED}",
        "",
        "Design:",
        "  Outer test subjects remain untouched.",
        "  Inner train/validation are created only from",
        "  the corresponding outer training subjects.",
        "  Diagnosis + acquisition source are used for",
        "  stratification.",
        "",
        "Outer fold sizes:",
    ]

    for outer_fold in range(
        1,
        OUTER_FOLDS + 1,
    ):

        outer_test_count = int(
            (
                outer_df["fold"]
                == outer_fold
            ).sum()
        )

        outer_train_count = (
            EXPECTED_SUBJECTS
            - outer_test_count
        )

        report_lines.append(
            f"  Outer fold {outer_fold}: "
            f"train={outer_train_count}, "
            f"test={outer_test_count}"
        )

    report_lines.extend(
        [
            "",
            "Inner split sizes:",
        ]
    )

    for _, row in summary_df.iterrows():

        report_lines.append(
            f"  Outer {int(row['outer_fold'])}, "
            f"Inner {int(row['inner_fold'])}: "
            f"train={int(row['inner_train_subjects'])}, "
            f"validation="
            f"{int(row['inner_validation_subjects'])}, "
            f"outer_test="
            f"{int(row['outer_test_subjects'])}"
        )

    report_lines.extend(
        [
            "",
            "Validation errors:",
        ]
    )

    all_errors = (
        outer_errors
        + nested_errors
    )

    if all_errors:

        report_lines.extend(
            f"  - {error}"
            for error in all_errors
        )

        final_status = "FAIL"

    else:

        report_lines.append(
            "  None"
        )

        final_status = "PASS"

    report_lines.extend(
        [
            "",
            "Protection checks:",
            "  Existing baseline 70/15/15 split: UNMODIFIED",
            "  Existing baseline CNN model: UNMODIFIED",
            "  Existing outer CV assignments: READ ONLY",
            "  CNN training: NOT PERFORMED",
            "",
            f"Master assignments : "
            f"{MASTER_ASSIGNMENTS_FILE}",
            f"Summary            : "
            f"{SUMMARY_FILE}",
            f"Report             : "
            f"{VALIDATION_REPORT}",
            "",
            f"FINAL STATUS: {final_status}",
        ]
    )

    VALIDATION_REPORT.write_text(
        "\n".join(report_lines),
        encoding="utf-8",
    )

    # --------------------------------------------------------
    # Console output
    # --------------------------------------------------------

    print()
    print("=" * 72)
    print("NESTED CV SUMMARY")
    print("=" * 72)
    print()

    print(
        summary_df.to_string(
            index=False
        )
    )

    print()
    print(
        f"Master assignments : "
        f"{MASTER_ASSIGNMENTS_FILE}"
    )

    print(
        f"Summary            : "
        f"{SUMMARY_FILE}"
    )

    print(
        f"Report             : "
        f"{VALIDATION_REPORT}"
    )

    print()

    if all_errors:

        print(
            f"FINAL STATUS: FAIL "
            f"({len(all_errors)} issue(s))"
        )

        raise SystemExit(1)

    print(
        "FINAL STATUS: PASS"
    )


if __name__ == "__main__":
    main()